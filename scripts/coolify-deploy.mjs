#!/usr/bin/env node
/**
 * Deploy the institution through the Coolify API: project, Docker Compose
 * resource, environment variables, both domains, then a deploy.
 *
 * Everything it needs is in one gitignored file, `.env.coolify`, so no token is
 * ever passed on a command line or pasted into a shell:
 *
 *   node scripts/coolify-deploy.mjs --init      # write .env.coolify with generated secrets
 *   node scripts/coolify-deploy.mjs --dry-run   # print every request, send none
 *   node scripts/coolify-deploy.mjs             # apply, then deploy
 *
 * Idempotent: an existing project, application and env var are reused, and a
 * re-run only updates what differs. `--init` never overwrites an existing file,
 * because overwriting it would rotate SESSION_SECRET out from under the live
 * session cookies.
 *
 * Coolify's API server is `http://192.168.1.85:8000` in this estate —
 * `deploy.innotel.us` reaches the same instance through the edge, where
 * Authentik's outpost answers before the API does and redirects a bearer token
 * to a login page. Talk to the instance directly and the outpost is not in the
 * path at all. See deploy/coolify/README.md.
 */
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { resolve } from 'node:path';

const ROOT = resolve(import.meta.dirname, '..');
const ENV_FILE = resolve(ROOT, '.env.coolify');
const TEMPLATE = resolve(ROOT, 'deploy/coolify/.env.coolify.example');

const args = new Set(process.argv.slice(2));
const DRY = args.has('--dry-run');
const INIT = args.has('--init');

// ── configuration ───────────────────────────────────────────────────────────
/** Read KEY=value pairs without interpolating anything. */
function readEnvFile(file) {
  const values = {};
  if (!existsSync(file)) return values;
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    if (!line.trim() || line.trimStart().startsWith('#')) continue;
    const match = /^\s*([A-Z0-9_]+)\s*=\s*(.*)$/.exec(line);
    if (!match) continue;
    values[match[1]] = match[2].trim().replace(/^["']|["']$/g, '');
  }
  return values;
}

/** A URL-safe password with no shell-quoting surprises. */
function password(length = 28) {
  const alphabet = 'abcdefghijkmnopqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789-_';
  const bytes = randomBytes(length);
  return Array.from(bytes, (byte) => alphabet[byte % alphabet.length]).join('');
}

function writeEnvFile(values) {
  const lines = [
    '# Generated by scripts/coolify-deploy.mjs --init. Gitignored: never commit.',
    '#',
    '# COOLIFY_TOKEN is the one value this cannot generate: Keys & Tokens ->',
    '# API tokens -> Create New Token (permission `write`), pasted in once.',
    '',
  ];
  for (const [key, value] of Object.entries(values)) {
    if (key === 'COOLIFY_TOKEN' && !value) {
      lines.push(`${key}=`, '# ^ paste the token here, then run: node scripts/coolify-deploy.mjs');
      continue;
    }
    lines.push(`${key}="${value}"`);
  }
  writeFileSync(ENV_FILE, lines.join('\n') + '\n', { mode: 0o600 });
  try {
    chmodSync(ENV_FILE, 0o600);
  } catch {
    // Windows has no POSIX mode; the file is still gitignored.
  }
}

if (INIT) {
  if (existsSync(ENV_FILE)) {
    console.error(`coolify-deploy: ${ENV_FILE} already exists — not overwriting it.`);
    console.error('  Delete it first if you really want new secrets (that invalidates live sessions).');
    process.exit(2);
  }
  const seed = readEnvFile(TEMPLATE);
  writeEnvFile({
    COOLIFY_BASE_URL: seed.COOLIFY_BASE_URL || 'http://192.168.1.85:8000',
    COOLIFY_TOKEN: '',
    COOLIFY_PROJECT: seed.COOLIFY_PROJECT || 'atheniq',
    COOLIFY_SERVER: seed.COOLIFY_SERVER || 'i2-local',
    COOLIFY_GIT_REPOSITORY: seed.COOLIFY_GIT_REPOSITORY || 'https://github.com/innotelinc/atheniq-evo.git',
    COOLIFY_GIT_BRANCH: seed.COOLIFY_GIT_BRANCH || 'main',
    COOLIFY_COMPOSE_LOCATION: seed.COOLIFY_COMPOSE_LOCATION || '/docker-compose.coolify.yml',
    INSTITUTION_ORIGIN: 'https://atheniq.innotel.site',
    REGISTRAR_ORIGIN: 'https://registrar.innotel.site',
    SESSION_SECRET: randomBytes(32).toString('hex'),
    REGISTRAR_EMAIL: 'registrar@atheniq.institute',
    REGISTRAR_PASSWORD: password(),
    MAIL_PROVIDER: 'local',
    MAIL_DOMAIN: 'atheniq.institute',
  });
  console.log(`coolify-deploy: wrote ${ENV_FILE} (mode 0600, gitignored)`);
  console.log('  generated: SESSION_SECRET (32 bytes), REGISTRAR_PASSWORD (28 chars)');
  console.log('  still empty: COOLIFY_TOKEN — paste Coolify\'s API token there.');
  process.exit(0);
}

const env = { ...readEnvFile(TEMPLATE), ...readEnvFile(ENV_FILE) };
// A variable already exported overrides the file, so one deploy can target a
// different server or source without editing a file that holds secrets.
for (const key of Object.keys(env)) {
  if (process.env[key]) env[key] = process.env[key];
}
const base = (env.COOLIFY_BASE_URL || '').replace(/\/+$/, '');
const token = env.COOLIFY_TOKEN || '';
const projectName = env.COOLIFY_PROJECT || 'atheniq';
const serverName = env.COOLIFY_SERVER || 'i2-local';
const appName = 'atheniq';
const domains = [(env.INSTITUTION_ORIGIN || 'https://atheniq.innotel.site'),
  (env.REGISTRAR_ORIGIN || 'https://registrar.innotel.site')];

if (!base) {
  console.error('coolify-deploy: COOLIFY_BASE_URL is empty. Run --init, or set it in .env.coolify.');
  process.exit(2);
}
if (/deploy\.innotel\.us/.test(base)) {
  console.error('coolify-deploy: COOLIFY_BASE_URL names the edge, where Authentik answers first and');
  console.error('  redirects the API. Use the instance directly: http://192.168.1.85:8000');
  process.exit(2);
}
if (!token && !DRY) {
  console.error('coolify-deploy: COOLIFY_TOKEN is empty in .env.coolify.');
  console.error('  Coolify UI -> Keys & Tokens -> API tokens -> Create New Token (write).');
  process.exit(2);
}
for (const key of ['SESSION_SECRET', 'REGISTRAR_PASSWORD']) {
  if (!env[key]) {
    console.error(`coolify-deploy: ${key} is empty in .env.coolify — run --init (or restore it).`);
    process.exit(2);
  }
}

// ── API ─────────────────────────────────────────────────────────────────────
const api = `${base}/api/v1`;

/** Names whose values must never reach a terminal, not even in a dry run. */
const SECRET_KEY = /(SECRET|PASSWORD|TOKEN)/i;

/** A body safe to print: secret values become their length. */
function redact(body) {
  if (!body || typeof body !== 'object') return body;
  const copy = { ...body };
  if (typeof copy.key === 'string' && SECRET_KEY.test(copy.key)) {
    if (typeof copy.value === 'string' && copy.value) copy.value = `<${copy.value.length} chars>`;
    return copy;
  }
  for (const [key, value] of Object.entries(copy)) {
    if (SECRET_KEY.test(key) && typeof value === 'string' && value) copy[key] = `<${value.length} chars>`;
  }
  return copy;
}

async function call(method, path, body) {
  const url = `${api}${path}`;
  if (DRY) {
    console.log(`  DRY  ${method} ${path}${body ? ' ' + JSON.stringify(redact(body)) : ''}`);
    return { dry: true };
  }
  let response;
  try {
    response = await fetch(url, {
      method,
      headers: {
        Authorization: `Bearer ${token}`,
        Accept: 'application/json',
        ...(body ? { 'Content-Type': 'application/json' } : {}),
      },
      ...(body ? { body: JSON.stringify(body) } : {}),
      signal: AbortSignal.timeout(30_000),
    });
  } catch (error) {
    const reason = error?.cause?.code || error?.message || String(error);
    throw new Error(`${method} ${path} did not answer (${reason}). Is the panel at ${base} up?`);
  }
  const text = await response.text();
  let parsed;
  try {
    parsed = text ? JSON.parse(text) : null;
  } catch {
    parsed = text;
  }
  if (!response.ok) {
    throw new Error(`${method} ${path} → ${response.status} ${typeof parsed === 'string' ? parsed.slice(0, 200) : JSON.stringify(parsed).slice(0, 200)}`);
  }
  return parsed;
}

const step = (message) => console.log(`\n== ${message}`);

// ── 1. the panel answers and accepts the token ──────────────────────────────
step(`Coolify at ${base}`);
const health = await call('GET', '/health');
if (!DRY) console.log(`  health: ${typeof health === 'string' ? health.slice(0, 40) : JSON.stringify(health).slice(0, 40)}`);

// ── 2. the destination server ───────────────────────────────────────────────
step(`Server "${serverName}"`);
const servers = DRY ? [] : await call('GET', '/servers');
const server = Array.isArray(servers)
  ? servers.find((item) => item.name === serverName || item.uuid === serverName)
  : null;
if (!DRY && !server) {
  const names = (servers ?? []).map((item) => item.name).join(', ') || '(none)';
  throw new Error(`no server named "${serverName}" — the instance knows: ${names}`);
}
if (server) console.log(`  ${server.name} → ${server.ip ?? server.uuid}`);
const serverUuid = server?.uuid ?? '<server-uuid>';

// ── 3. the project ──────────────────────────────────────────────────────────
step(`Project "${projectName}"`);
const projects = DRY ? [] : await call('GET', '/projects');
let project = Array.isArray(projects) ? projects.find((item) => item.name === projectName) : null;
if (!DRY && !project) {
  project = await call('POST', '/projects', {
    name: projectName,
    description: 'AthenIQ Institute: public site and registrar (atheniq.innotel.site, registrar.innotel.site)',
  });
  console.log('  created');
} else if (project) {
  console.log(`  exists → ${project.uuid}`);
}
const projectUuid = project?.uuid ?? '<project-uuid>';

// ── 4. the Docker Compose resource ──────────────────────────────────────────
step(`Resource "${appName}" (${env.COOLIFY_COMPOSE_LOCATION || '/docker-compose.coolify.yml'})`);
const applications = DRY ? [] : await call('GET', '/applications');
const found = Array.isArray(applications)
  ? applications.find((item) => item.name === appName && item.uuid !== undefined)
  : null;

// innotelinc/atheniq-evo is private, so the `/public` endpoint cannot clone it:
// Coolify has to read it through a GitHub App or a deploy key, whichever this
// instance has. Whichever is named wins; with neither, the public endpoint is
// used and the clone will fail on a private repository.
const source = env.COOLIFY_GITHUB_APP_UUID
  ? { path: '/applications/private-github-app', field: 'github_app_uuid', value: env.COOLIFY_GITHUB_APP_UUID }
  : env.COOLIFY_PRIVATE_KEY_UUID
    ? { path: '/applications/private-deploy-key', field: 'private_key_uuid', value: env.COOLIFY_PRIVATE_KEY_UUID }
    : { path: '/applications/public', field: null, value: null };

const createBody = {
  project_uuid: projectUuid,
  server_uuid: serverUuid,
  environment_name: 'production',
  git_repository: env.COOLIFY_GIT_REPOSITORY,
  git_branch: env.COOLIFY_GIT_BRANCH,
  ...(env.COOLIFY_GITHUB_APP_UUID ? { github_app_uuid: env.COOLIFY_GITHUB_APP_UUID } : {}),
  ...(env.COOLIFY_PRIVATE_KEY_UUID ? { private_key_uuid: env.COOLIFY_PRIVATE_KEY_UUID } : {}),
  build_pack: 'dockercompose',
  docker_compose_location: env.COOLIFY_COMPOSE_LOCATION || '/docker-compose.coolify.yml',
  ports_exposes: '8080',
  name: appName,
  description: 'AthenIQ Institute: public site and registrar',
  instant_deploy: false,
};

console.log(`  source: ${source.path}${source.field ? ` (${source.field} set)` : ' — private repositories need a GitHub App or deploy key'}`);

let application = found;
if (DRY) {
  await call('POST', source.path, createBody);
} else if (!application) {
  application = await call('POST', source.path, createBody);
  console.log(`  created → ${application.uuid}`);
} else {
  console.log(`  exists → ${application.uuid}`);
}
const appUuid = application?.uuid ?? '<application-uuid>';

// ── 5. the environment the service refuses to start without ─────────────────
const wanted = [
  ['SESSION_SECRET', env.SESSION_SECRET],
  ['REGISTRAR_EMAIL', env.REGISTRAR_EMAIL],
  ['REGISTRAR_PASSWORD', env.REGISTRAR_PASSWORD],
  ['MAIL_PROVIDER', env.MAIL_PROVIDER || 'local'],
  ['MAIL_DOMAIN', env.MAIL_DOMAIN || 'atheniq.institute'],
  ['INSTITUTION_ORIGIN', env.INSTITUTION_ORIGIN],
  ['REGISTRAR_ORIGIN', env.REGISTRAR_ORIGIN],
  ['TRUST_PROXY', 'true'],
  ['COOKIE_SECURE', 'true'],
  ...(env.STALWART_URL ? [['STALWART_URL', env.STALWART_URL]] : []),
  ...(env.STALWART_TOKEN ? [['STALWART_TOKEN', env.STALWART_TOKEN]] : []),
];
step(`Environment (${wanted.length} variables)`);
const existing = DRY ? [] : await call('GET', `/applications/${appUuid}/envs`);
const have = new Map((Array.isArray(existing) ? existing : []).map((row) => [row.key, row]));
for (const [key, value] of wanted) {
  if (!value) continue;
  if (have.has(key)) {
    // Values are returned in full by this endpoint; a same-value row is left
    // alone so re-runs do not touch a secret.
    if (have.get(key).value === value) {
      console.log(`  ${key}: present, unchanged`);
      continue;
    }
    await call('PATCH', `/applications/${appUuid}/envs`, { key, value, is_preview: false });
    console.log(`  ${key}: updated`);
    continue;
  }
  await call('POST', `/applications/${appUuid}/envs`, { key, value, is_preview: false, is_buildtime: false, is_runtime: true });
  console.log(`  ${key}: set`);
}

// ── 6. both hostnames on the one container ─────────────────────────────────
step(`Domains → ${domains.join(', ')}`);
// A compose application carries its domains per service, as one comma-separated
// string; the service name has to match docker-compose.coolify.yml's.
const composeDomains = [{ name: 'institution', domain: domains.join(',') }];
await call('PATCH', `/applications/${appUuid}`, { docker_compose_domains: composeDomains });
if (!DRY) console.log('  set on the `institution` service, internal port 8080');

// ── 7. deploy ──────────────────────────────────────────────────────────────
step('Deploy');
const deploy = await call('POST', `/deploy?uuid=${encodeURIComponent(appUuid)}&force=false`);
if (!DRY) {
  console.log(`  ${typeof deploy === 'string' ? deploy : JSON.stringify(deploy).slice(0, 200)}`);
}

if (DRY) {
  console.log('\ncoolify-deploy: dry run — nothing was sent.');
} else {
  console.log('\ncoolify-deploy: queued. Watch the build in Coolify, then verify:');
  console.log(`  curl -fsS https://atheniq.innotel.site/health`);
  console.log(`  curl -fsS -o /dev/null -w '%{http_code}\\n' https://atheniq.innotel.site/`);
  console.log(`  curl -fsS -o /dev/null -w '%{http_code}\\n' https://registrar.innotel.site/`);
}
